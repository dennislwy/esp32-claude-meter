Epaper::Epaper(const EpaperPins &pins) : pins_(pins) {}

void Epaper::begin()
{
  setupPins();
  initFull();

  // Write white to both RAM banks so partial refreshes start from a known base image
  clear();
  sendCommand(0x24);
  sendData(buffer_, FRAME_BYTES);
  sendCommand(0x26);
  sendData(buffer_, FRAME_BYTES);
  turnOnDisplay(0xC7);

  initPartial();
}

void Epaper::resume(const uint8_t *onScreen)
{
  setupPins();
  initPartial();

  // RAM 0x26 holds the image partial refreshes start from
  memcpy(buffer_, onScreen, FRAME_BYTES);
  setCursor(0, HEIGHT - 1);
  sendCommand(0x26);
  sendData(buffer_, FRAME_BYTES);
}

void Epaper::sleep()
{
  sendCommand(0x10); // deep sleep mode 1
  sendData(0x01);
}

void Epaper::clear()
{
  memset(buffer_, 0xFF, FRAME_BYTES);
}

void Epaper::setPixel(int x, int y, bool black)
{
  if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT)
  {
    return;
  }
  const size_t index = y * (WIDTH / 8) + (x >> 3);
  const uint8_t mask = 0x80 >> (x & 0x07);
  if (black)
  {
    buffer_[index] &= ~mask;
  }
  else
  {
    buffer_[index] |= mask;
  }
}

void Epaper::refresh()
{
  // Start each frame at the first row, whatever state an earlier write left the counter in
  setCursor(0, HEIGHT - 1);
  sendCommand(0x24);
  sendData(buffer_, FRAME_BYTES);
  turnOnDisplay(0xCF);
}

void Epaper::setupPins()
{
  pinMode(pins_.cs, OUTPUT);
  pinMode(pins_.dc, OUTPUT);
  pinMode(pins_.rst, OUTPUT);
  pinMode(pins_.busy, INPUT);
  digitalWrite(pins_.cs, HIGH);
  digitalWrite(pins_.rst, HIGH);
  SPI.begin(pins_.sck, -1, pins_.mosi, -1);
}

// Orientation and RAM addressing. Sent on every init: after the panel loses power (e.g. while the
// ESP32 is in deep sleep) the controller reverts to defaults, which draw the frame upside down.
void Epaper::configureRam()
{
  sendCommand(0x01); // driver output control: 200 gate lines, scan direction
  sendData(0xC7);
  sendData(0x00);
  sendData(0x01);

  sendCommand(0x11); // data entry mode: X increment, Y decrement
  sendData(0x01);
  setWindow(0, HEIGHT - 1, WIDTH - 1, 0);
  setCursor(0, HEIGHT - 1);
}

void Epaper::initFull()
{
  reset();
  sendCommand(0x12); // software reset
  waitUntilIdle();

  configureRam();

  sendCommand(0x3C); // border waveform
  sendData(0x01);

  sendCommand(0x18); // internal temperature sensor
  sendData(0x80);

  sendCommand(0x22); // load temperature and waveform
  sendData(0xB1);
  sendCommand(0x20);

  setCursor(0, HEIGHT - 1);
  waitUntilIdle();

  setLut(LUT_FULL);
}

void Epaper::initPartial()
{
  reset();
  configureRam();
  setLut(LUT_PARTIAL);

  sendCommand(0x37);
  const uint8_t displayOption[] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00};
  sendData(displayOption, sizeof(displayOption));

  sendCommand(0x3C); // border waveform
  sendData(0x80);

  sendCommand(0x22);
  sendData(0xC0);
  sendCommand(0x20);
  waitUntilIdle();
}

void Epaper::reset()
{
  digitalWrite(pins_.rst, HIGH);
  delay(50);
  digitalWrite(pins_.rst, LOW);
  delay(20);
  digitalWrite(pins_.rst, HIGH);
  delay(50);
  waitUntilIdle();
}

// BUSY is high while the controller is working
void Epaper::waitUntilIdle()
{
  const uint32_t start = millis();
  while (digitalRead(pins_.busy) == HIGH)
  {
    if (millis() - start > BUSY_TIMEOUT_MS)
    {
      Serial.println("e-paper busy timeout");
      return;
    }
    delay(5);
  }
}

void Epaper::sendCommand(uint8_t command)
{
  SPI.beginTransaction(EPD_SPI);
  digitalWrite(pins_.dc, LOW);
  digitalWrite(pins_.cs, LOW);
  SPI.transfer(command);
  digitalWrite(pins_.cs, HIGH);
  SPI.endTransaction();
}

void Epaper::sendData(uint8_t data)
{
  sendData(&data, 1);
}

void Epaper::sendData(const uint8_t *data, size_t len)
{
  SPI.beginTransaction(EPD_SPI);
  digitalWrite(pins_.dc, HIGH);
  digitalWrite(pins_.cs, LOW);
  SPI.writeBytes(data, len);
  digitalWrite(pins_.cs, HIGH);
  SPI.endTransaction();
}

void Epaper::setLut(const uint8_t *lut)
{
  sendCommand(0x32);
  sendData(lut, 153);
  waitUntilIdle();

  sendCommand(0x3F); // end option
  sendData(lut[153]);
  sendCommand(0x03); // gate voltage
  sendData(lut[154]);
  sendCommand(0x04); // source voltages
  sendData(&lut[155], 3);
  sendCommand(0x2C); // VCOM
  sendData(lut[158]);
}

void Epaper::setWindow(uint16_t xStart, uint16_t yStart, uint16_t xEnd, uint16_t yEnd)
{
  sendCommand(0x44);
  sendData((xStart >> 3) & 0xFF);
  sendData((xEnd >> 3) & 0xFF);

  sendCommand(0x45);
  sendData(yStart & 0xFF);
  sendData((yStart >> 8) & 0xFF);
  sendData(yEnd & 0xFF);
  sendData((yEnd >> 8) & 0xFF);
}

void Epaper::setCursor(uint16_t x, uint16_t y)
{
  sendCommand(0x4E);
  sendData(x & 0xFF);

  sendCommand(0x4F);
  sendData(y & 0xFF);
  sendData((y >> 8) & 0xFF);
}

void Epaper::turnOnDisplay(uint8_t sequence)
{
  sendCommand(0x22);
  sendData(sequence);
  sendCommand(0x20);
  waitUntilIdle();
}
